/**
 * Returns holiday details for a date string in YYYY-MM-DD format
 * @param {string} dateStr 
 * @returns {object|null}
 */
export function getIndianHoliday(dateStr) {
  if (!dateStr) return null;
  
  if (INDIAN_HOLIDAYS[dateStr]) {
    return INDIAN_HOLIDAYS[dateStr];
  }

  // Check recurring
  const monthDay = dateStr.slice(5); // "MM-DD"
  if (RECURRING_HOLIDAYS[monthDay]) {
    return RECURRING_HOLIDAYS[monthDay];
  }

  return null;
}

/**
 * Checks if a date string is an Indian holiday or Sunday (official school off)
 * @param {string} dateStr 
 * @returns {boolean}
 */
export function isSchoolOffDay(dateStr) {
  if (!dateStr) return false;
  const d = new Date(dateStr + 'T00:00:00');
  if (d.getDay() === 0) return true; // Sunday
  return !!getIndianHoliday(dateStr);
}
